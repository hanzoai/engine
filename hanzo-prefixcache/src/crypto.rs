//! Clean-room, zero-dependency cryptographic hashing (FIPS 180-4 SHA-256),
//! IEEE 802.3 CRC32 checksums, and constant-time digest comparison.

use std::fmt;

/// A 256-bit SHA-256 digest used for cache keys, compatibility profiles, and snapshot integrity.
#[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]
pub struct Digest256(pub [u8; 32]);

impl Digest256 {
    /// All-zero sentinel digest (used for root parent pointers).
    pub const ZERO: Self = Self([0u8; 32]);

    /// Construct from a raw 32-byte array.
    #[must_use]
    pub const fn from_bytes(bytes: [u8; 32]) -> Self {
        Self(bytes)
    }

    /// Borrow the underlying 32 bytes.
    #[must_use]
    pub const fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }

    /// Constant-time equality comparison against another digest.
    #[must_use]
    pub fn ct_eq(&self, other: &Self) -> bool {
        ct_eq_32(&self.0, &other.0)
    }

    /// Encode as a lowercase 64-character hexadecimal string.
    #[must_use]
    pub fn to_hex(&self) -> String {
        const HEX: &[u8; 16] = b"0123456789abcdef";
        let mut out = String::with_capacity(64);
        for &b in &self.0 {
            out.push(HEX[(b >> 4) as usize] as char);
            out.push(HEX[(b & 0x0f) as usize] as char);
        }
        out
    }

    /// Two-character hex shard directory prefix for filesystem layout.
    #[must_use]
    pub fn shard_prefix(&self) -> String {
        const HEX: &[u8; 16] = b"0123456789abcdef";
        let b = self.0[0];
        let mut out = String::with_capacity(2);
        out.push(HEX[(b >> 4) as usize] as char);
        out.push(HEX[(b & 0x0f) as usize] as char);
        out
    }
}

impl fmt::Debug for Digest256 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "Digest256({})", &self.to_hex()[..16])
    }
}

impl fmt::Display for Digest256 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.to_hex())
    }
}

/// Constant-time equality comparison for two 32-byte arrays.
#[must_use]
pub fn ct_eq_32(a: &[u8; 32], b: &[u8; 32]) -> bool {
    let mut diff: u8 = 0;
    for i in 0..32 {
        diff |= a[i] ^ b[i];
    }
    diff == 0
}

